const MEMBERS = { ...SEOUL, ...GG };
const lookup =(tbl, name, exact) => {
	for (const [r, list] of Object.entries(tbl))
		for (const n of list.split(' ')) if (exact ? name === n : name.startsWith(n)) return r;
	throw new Error('unmapped ' + name);
};
const regionOf = ({ code, name }) => {
	const p = code.slice(0, 2);
	if (p === '11') return lookup(SEOUL, name, true);
	if (p === '31') return lookup(GG, name, false);
	return PROV[+p];
};

const K = 100;
const C = Math.cos((36 * Math.PI) / 180);
const proj = ([lon, lat]) => [(lon - 124.5) * C * K, (38.7 - lat) * K];
const sqd = (p, a, b) => {
	const dx = b[0] - a[0];
	const dy = b[1] - a[1];
	const l = dx * dx + dy * dy;
	let t = l ? ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l : 0;
	t = Math.max(0, Math.min(1, t));
	return (p[0] - a[0] - t * dx) ** 2 + (p[1] - a[1] - t * dy) ** 2;
};
const dp = (pts, e2) => {
	if (pts.length < 3) return pts;
	let m = 0;
	let i = 0;
	for (let k = 1; k < pts.length - 1; k++) {
		const d = sqd(pts[k], pts[0], pts.at(-1));
		if (d > m) {
			m = d;
			i = k;
		}
	}
	return m > e2
		? [...dp(pts.slice(0, i + 1), e2).slice(0, -1), ...dp(pts.slice(i), e2)]
		: [pts[0], pts.at(-1)];
};
const area = (r) =>
	Math.abs(
		r.reduce((s, p, i) => {
			const q = r[i - 1] ?? r.at(-1);
			return s + q[0] * p[1] - p[0] * q[1];
		}, 0) / 2
	);

const geo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const f of geo.features) {
	const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
	let d = '';
	for (const poly of polys)
		for (const ring of poly) {
			const r = dp(ring.map(proj), 0.4 * 0.4);
			if (r.length < 4 || area(r) < 3) continue;
			d += 'M' + r.map((p) => p[0].toFixed(1) + ' ' + p[1].toFixed(1)).join('L') + 'Z';
		}
	(out[regionOf(f.properties)] ??= []).push(d);
}
const regions = Object.entries(out).map(([name, d]) => ({ name, d: d.join('') }));
